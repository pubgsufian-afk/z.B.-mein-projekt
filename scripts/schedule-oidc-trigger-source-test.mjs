assert.match(source, /Netlify\.env\.get/)
assert.match(source, /scheduleAssistant/)
assert.match(source, /assistantRequestBody/)
assert.match(source, /command\.action === 'list-shifts'/)
assert.match(source, /command\.action === 'find-duplicates'/)
