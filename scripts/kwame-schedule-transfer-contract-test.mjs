import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const api = readFileSync('netlify/functions/registrations.mts', 'utf8')
const db = readFileSync('netlify/functions/_shared/schedule-identity-transfer.mts', 'utf8')
const ui = readFileSync('frontend/src/employee-role-management-auto.js', 'utf8')

assert.match(api, /access\.current\.role !== 'owner'/, 'Only the Hauptadmin can migrate shifts')
assert.match(api, /verifyRequestOrigin\(request\)/, 'Origin checks must be enforced')
assert.match(api, /normalizedText\(source\.fullName \|\| source\.name\) !== '12'/)
assert.match(api, /normalizedText\(target\.fullName \|\| target\.name\) !== 'kwame akakpo'/)
assert.match(api, /targetAccess\?\.status !== 'active'/, 'Target requires a confirmed active login')
assert.match(api, /sourceUserId === targetUserId/, 'Cannot transfer to the same account')
assert.match(api, /preview-kwame-schedule-transfer/)
assert.match(api, /confirm-kwame-schedule-transfer/)
assert.match(api, /schedule-identity-transfer\.mts/)
assert.match(ui, /currentSession\.role !== 'owner'/)
assert.match(ui, /window\.confirm\(question\)/, 'A human must approve the transfer')
assert.match(ui, /targetUserId/, 'The destination is a real account ID, never a text-only rename')

assert.match(db, /BEGIN TRANSACTION ISOLATION LEVEL SERIALIZABLE/)
assert.match(db, /FOR UPDATE/, 'Original shifts must be locked')
assert.match(db, /destination\.start_time < guest\.end_time/)
assert.match(db, /guest\.start_time < destination\.end_time/)
assert.match(db, /if \(input\.preview \|\| result\.conflicts\.length \|\| !result\.shiftCount\)/)
assert.match(db, /ROLLBACK/, 'Preview and collision must not write changes')
assert.match(db, /UPDATE schedule_shifts/)
assert.match(db, /SET employee_user_id = \$2/)
assert.match(db, /employee_name = \$3/)
assert.match(db, /schedule_audit_log/, 'Transfer must be auditable')
assert.doesNotMatch(db, /DELETE FROM schedule_shifts/i, 'Never delete original shift records')
assert.doesNotMatch(db, /status\s*=\s*'draft'/, 'Publication state must not be reset')
assert.doesNotMatch(db, /UPDATE attendance_/i, 'Attendance must not be silently rewritten')
console.log('PASS: Kwame identity schedule transfer is owner-only, previewed, collision-safe, transactional, and audited.')
